// Bundles the Esther cloud function (src/cloud/function.ts + the shared sentence reader) into one file
// you can paste into Supabase: supabase/functions/esther/index.ts
import { build } from 'rolldown';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
mkdirSync('supabase/functions/esther', { recursive: true });
await build({ input: 'src/cloud/function.ts', platform: 'neutral', output: { file: 'supabase/functions/esther/index.ts', format: 'esm' } });
const out = 'supabase/functions/esther/index.ts';
writeFileSync(out, `// Esther cloud function, build ${JSON.parse(readFileSync('package.json', 'utf8')).version}. Generated by npm run build:cloud from src/cloud/function.ts — edit that, not this.\n` + readFileSync(out, 'utf8'));
console.log('wrote', out, readFileSync(out, 'utf8').length, 'bytes');
