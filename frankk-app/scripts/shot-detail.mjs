import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: process.env.CHROME, args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 1536, height: 900 } });
await p.goto('http://127.0.0.1:5173/?today=2026-10-14'); await p.waitForTimeout(1000);
await p.getByRole('button', { name: 'Music', exact: true }).click(); await p.waitForTimeout(800);
await p.screenshot({ path: 'docs/screens/music-focus.png' });
await p.getByRole('button', { name: 'Home', exact: true }).click(); await p.waitForTimeout(500);
await p.getByRole('button', { name: 'Appearance' }).first().click(); await p.waitForTimeout(300);
await p.locator('.slider', { hasText: 'Panel translucency' }).locator('input').fill('0.55');
await p.locator('.slider', { hasText: 'Darken art' }).locator('input').fill('0.55');
await p.waitForTimeout(300);
await p.screenshot({ path: 'docs/screens/appearance.png' });
await b.close();
